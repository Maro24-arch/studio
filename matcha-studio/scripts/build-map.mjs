// Generates src/data/japanMap.ts from Natural Earth (via world-atlas, public domain).
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoMercator, geoPath, geoCentroid, geoArea } from 'd3-geo'

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-10m.json', 'utf8'))
const jp = feature(topo, topo.objects.countries).features.find((f) => f.properties.name === 'Japan')
const polys = jp.geometry.type === 'MultiPolygon' ? jp.geometry.coordinates : [jp.geometry.coordinates]
const kept = polys.filter((p) => {
  const g = { type: 'Polygon', coordinates: p }
  const [lon, lat] = geoCentroid(g)
  return lon > 128 && lon < 147 && lat > 30 && lat < 46 && geoArea(g) > 2e-6
})
const geom = { type: 'MultiPolygon', coordinates: kept }
const W = 640, H = 760
const proj = geoMercator().fitExtent([[24, 24], [W - 24, H - 24]], geom)
const d = geoPath(proj).digits ? geoPath(proj).digits(1)(geom) : geoPath(proj)(geom)
const out = `// AUTO-GENERATED by scripts/build-map.mjs — Natural Earth data (public domain) via world-atlas.
export const JAPAN_MAP = {
  width: ${W},
  height: ${H},
  scale: ${proj.scale()},
  translate: [${proj.translate().join(', ')}] as [number, number],
  center: [${proj.center().join(', ')}] as [number, number],
  path: ${JSON.stringify(d)},
}
`
writeFileSync('src/data/japanMap.ts', out)
console.log('polygons kept', kept.length, 'path bytes', d.length)
